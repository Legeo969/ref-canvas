import { describe, expect, it } from "vitest";
import {
  applyResidual,
  createResidualLut,
  sampleResidual,
  writeCubeText,
} from "../../../../src/shared/match/residual-lut";

function cornerResidual(dimension: number) {
  const lut = createResidualLut(dimension);
  const last = dimension ** 3 - 1;
  lut.data.set([0.1, 0.2, 0.3], 0);
  lut.data.set([-0.05, 0.02, 0.4], last * 3);
  return lut;
}

describe("residual sampling", () => {
  it("samples lattice corners exactly", () => {
    const lut = cornerResidual(5);
    expect(sampleResidual(lut, 0, 0, 0)).toEqual([expect.closeTo(0.1, 6), expect.closeTo(0.2, 6), expect.closeTo(0.3, 6)]);
    expect(sampleResidual(lut, 1, 1, 1)[2]).toBeCloseTo(0.4, 6);
  });

  it("uses border lookup outside the unit cube", () => {
    const lut = cornerResidual(5);
    expect(sampleResidual(lut, -3, 0, 0)).toEqual(sampleResidual(lut, 0, 0, 0));
    expect(sampleResidual(lut, 1, 4, 1)).toEqual(sampleResidual(lut, 1, 1, 1));
  });

  it("interpolates trilinearly between corners", () => {
    const lut = createResidualLut(3);
    lut.data.set([0, 0, 0], 0);
    const last = 26 * 3;
    lut.data.set([1, 1, 1], last);
    const middle = sampleResidual(lut, 0.75, 0.75, 0.75);
    expect(middle[0]).toBeCloseTo(0.125, 6);
  });

  it("applies the residual on top of the input colour", () => {
    const lut = cornerResidual(5);
    expect(applyResidual(lut, 0, 0, 0)[0]).toBeCloseTo(0.1, 6);
  });

  it("rejects malformed volumes", () => {
    expect(() => createResidualLut(1)).toThrow("LUT_DIMENSION_INVALID");
    expect(() => createResidualLut(4, new Float32Array(10))).toThrow("LUT_DATA_LENGTH_INVALID");
  });
});

describe("writeCubeText", () => {
  it("writes a Resolve header and one row per lattice point", () => {
    const text = writeCubeText(cornerResidual(3), {
      title: "Reference match",
      comments: ["Input domain: Rec.709 Gamma 2.4."],
    });
    const lines = text.split("\n");
    expect(lines[0]).toBe("# Generated by RefCanvas reference matching");
    expect(lines).toContain('TITLE "Reference match"');
    expect(lines).toContain("LUT_3D_SIZE 3");
    const rows = lines.filter((line) => line.trim() && !line.startsWith("#") && !/^[A-Z][A-Z0-9_]* /.test(line));
    expect(rows).toHaveLength(27);
  });

  it("writes red fastest and bakes final output values", () => {
    const text = writeCubeText(cornerResidual(3));
    const rows = text
      .split("\n")
      .filter((line) => line.trim() && !line.startsWith("#") && !/^[A-Z][A-Z0-9_]* /.test(line))
      .map((line) => line.trim().split(" ").map(Number));
    expect(rows[0]).toEqual([expect.closeTo(0.1, 6), expect.closeTo(0.2, 6), expect.closeTo(0.3, 6)]);
    // Interior lattice points carry no residual in this volume, so their rows
    // are plain identity values.
    expect(rows[1][0]).toBeCloseTo(0.5, 6);
    expect(rows[1][1]).toBeCloseTo(0, 6);
    expect(rows[3][1]).toBeCloseTo(0.5, 6);
    expect(rows[9][2]).toBeCloseTo(0.5, 6);
    expect(rows[26]).toEqual([expect.closeTo(0.95, 6), expect.closeTo(1.02, 6), expect.closeTo(1.4, 6)]);
  });

  it("clamps output when display-referred limits are requested", () => {
    const lut = createResidualLut(2);
    lut.data.set([0.5, -0.5, 0], 0);
    const text = writeCubeText(lut, { outputLimits: [0, 1] });
    expect(text).toContain("1.0000000 0.0000000 0.0000000");
  });

  it("rejects inverted output limits", () => {
    expect(() => writeCubeText(cornerResidual(2), { outputLimits: [1, 0] })).toThrow(
      "LUT_OUTPUT_LIMITS_INVALID",
    );
  });
});
